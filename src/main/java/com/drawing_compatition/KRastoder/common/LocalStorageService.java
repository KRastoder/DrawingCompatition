package com.drawing_compatition.KRastoder.common;

import org.springframework.transaction.annotation.Transactional;

import java.util.Optional;
import java.util.UUID;

/**
 * Local database storage implementation using a separate blobs table.
 * Used for development and testing.
 * Bean is registered via StorageConfig.
 */
@Transactional
public class LocalStorageService implements StorageService {

    private final StoredBlobRepository blobRepository;

    public LocalStorageService(StoredBlobRepository blobRepository) {
        this.blobRepository = blobRepository;
    }

    @Override
    public String store(String contentType, byte[] data) {
        String storageKey = UUID.randomUUID().toString();
        StoredBlob blob = new StoredBlob(storageKey, contentType, data);
        blobRepository.save(blob);
        return storageKey;
    }

    @Override
    public Optional<StoredObject> retrieve(String storageKey) {
        if (storageKey == null || storageKey.isBlank()) {
            return Optional.empty();
        }
        return blobRepository.findByStorageKey(storageKey)
                .map(blob -> new StoredObject(blob.getData(), blob.getContentType(), blob.getData().length));
    }

    @Override
    public boolean delete(String storageKey) {
        if (storageKey == null || storageKey.isBlank()) {
            return false;
        }
        return blobRepository.findByStorageKey(storageKey)
                .map(blob -> {
                    blobRepository.delete(blob);
                    return true;
                })
                .orElse(false);
    }

    @Override
    public boolean exists(String storageKey) {
        if (storageKey == null || storageKey.isBlank()) {
            return false;
        }
        return blobRepository.findByStorageKey(storageKey).isPresent();
    }

    @Override
    public String getPublicUrl(String storageKey) {
        // For local storage, URLs are generated by the controllers based on entity IDs
        return null;
    }
}